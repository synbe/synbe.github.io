#!/usr/bin/env python3
"""Scan assets/ directory and generate index.html with responsive file links."""

import os
import html
from pathlib import Path

ASSETS_DIR = Path(__file__).resolve().parent / "assets"
OUTPUT = Path(__file__).resolve().parent / "index.html"

# ── helpers ──────────────────────────────────────────────────────────

def human_size(bytes_: int) -> str:
    """Return human-readable file size."""
    for unit in ("B", "KB", "MB", "GB"):
        if bytes_ < 1024:
            return f"{bytes_:.1f} {unit}"
        bytes_ /= 1024
    return f"{bytes_:.1f} TB"


# ── gather files ─────────────────────────────────────────────────────

if not ASSETS_DIR.is_dir():
    print(f"❌ Directory not found: {ASSETS_DIR}")
    raise SystemExit(1)

files = []
for entry in sorted(ASSETS_DIR.iterdir(), key=lambda p: p.name.lower()):
    if entry.is_file():
        stat = entry.stat()
        files.append({
            "name": entry.name,
            "size": stat.st_size,
            "size_hr": human_size(stat.st_size),
        })

# ── render HTML ──────────────────────────────────────────────────────

total_size = sum(f["size"] for f in files)

html_content = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Assets Index</title>
  <style>
    *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
    body {{
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, "Noto Sans SC", sans-serif;
      background: #f5f5f7;
      color: #1d1d1f;
      padding: 2rem 1rem;
      min-height: 100vh;
      display: flex;
      flex-direction: column;
      align-items: center;
    }}
    .container {{ max-width: 720px; width: 100%; }}
    header {{
      margin-bottom: 2rem;
      text-align: center;
    }}
    header h1 {{
      font-size: 1.6rem;
      font-weight: 600;
      letter-spacing: -0.02em;
    }}
    header p {{
      margin-top: 0.3rem;
      font-size: 0.85rem;
      color: #86868b;
    }}
    .grid {{
      display: grid;
      grid-template-columns: 1fr;
      gap: 6px;
    }}
    .item {{
      display: flex;
      align-items: center;
      gap: 0.75rem;
      background: #fff;
      border-radius: 12px;
      padding: 0.75rem 1rem;
      text-decoration: none;
      color: inherit;
      transition: background 0.15s, box-shadow 0.15s;
      border: 1px solid rgba(0,0,0,0.04);
    }}
    .item:hover {{
      background: #e8e8ed;
      box-shadow: 0 1px 4px rgba(0,0,0,0.06);
    }}
    .item .idx {{ font-size: 0.82rem; color: #c7c7cc; min-width: 1.8rem; text-align: right; font-variant-numeric: tabular-nums; }}
    .item .info {{ flex: 1; min-width: 0; }}
    .item .name {{
      font-size: 0.95rem;
      font-weight: 500;
      white-space: nowrap;
      overflow: hidden;
      text-overflow: ellipsis;
    }}
    .item .meta {{
      font-size: 0.78rem;
      color: #86868b;
      margin-top: 0.1rem;
    }}
    .item .size {{ flex-shrink: 0; font-size: 0.82rem; color: #86868b; }}
    footer {{
      margin-top: 2.5rem;
      text-align: center;
      font-size: 0.78rem;
      color: #86868b;
    }}
    @media (max-width: 480px) {{
      body {{ padding: 1rem 0.6rem; }}
      header h1 {{ font-size: 1.3rem; }}
      .item {{ padding: 0.6rem 0.75rem; border-radius: 10px; }}
    }}
  </style>
</head>
<body>
<div class="container">
  <header>
    <h1>Assets</h1>
    <p>{len(files)} files · {human_size(total_size)} total</p>
  </header>
  <div class="grid">
"""
for i, f in enumerate(files, 1):
    escaped = html.escape(f["name"])
    html_content += f"""    <a class="item" href="assets/{escaped}" download>
      <span class="idx">{i}</span>
      <span class="info">
        <span class="name">{escaped}</span>
        <span class="meta">{f["size_hr"]}</span>
      </span>
    </a>
"""

html_content += """  </div>
  <footer>
    Generated by <code>generate_index.py</code>
  </footer>
</div>
</body>
</html>
"""

# ── write ────────────────────────────────────────────────────────────

OUTPUT.write_text(html_content, encoding="utf-8")
print(f"✅ index.html generated — {len(files)} files linked.")
